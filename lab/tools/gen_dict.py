# fm-1-chimera-vocal: the firmware's built-in pronunciations, CMUdict's entries for the words in common_words.txt, as
# a sorted C table for engine/ch_speech.c (binary search). The dictionary is CHIMERA's copy of CMUdict
# (external/chimera-vocal-synth/public/data/cmudict.txt.gz, "word<TAB>PHONES"), BSD-licensed (its notice is kept in
# the header).
#
#   gen_dict.py tools/common_words.txt ../external/chimera-vocal-synth/public/data/cmudict.txt.gz > ../engine/ch_dict_data.h
import gzip
import sys


def main(words_path, dict_path):
    words = []
    for line in open(words_path, encoding="utf-8"):
        line = line.split("#", 1)[0]
        words += line.split()
    want = set(w.lower() for w in words)
    d = {}
    for line in gzip.open(dict_path, "rt", encoding="utf-8"):
        line = line.rstrip("\n")
        if "\t" in line:
            w, p = line.split("\t", 1)
            if w in want and w not in d:
                d[w] = p
    missing = sorted(want - set(d))
    if missing:
        sys.stderr.write("not in the dictionary: %s\n" % " ".join(missing))
    entries = sorted(d.items(), key=lambda e: e[0].encode())
    size = sum(len(w) + len(p) + 2 for w, p in entries)
    out = [
        "/* SPDX-License-Identifier: BSD-2-Clause (CMUdict's licence: LICENSES/CMUdict.txt)",
        " * Generated by lab/tools/gen_dict.py from CMUdict (CHIMERA's copy): do not edit. %d words, ~%d bytes of text."
        % (len(entries), size),
        " *",
        " * Copyright (C) 1993-2015 Carnegie Mellon University. All rights reserved.",
        " * Redistribution and use in source and binary forms, with or without modification, are permitted provided that",
        " * the following conditions are met: 1. Redistributions of source code must retain the above copyright notice,",
        " * this list of conditions and the following disclaimer. The contents of this file are deemed to be source code.",
        " * 2. Redistributions in binary form must reproduce the above copyright notice, this list of conditions and the",
        " * following disclaimer in the documentation and/or other materials provided with the distribution.",
        " * This work was supported in part by funding from the Defense Advanced Research Projects Agency, the Office of",
        " * Naval Research and the National Science Foundation of the United States of America, and by member companies",
        " * of the Carnegie Mellon Sphinx Speech Consortium. We acknowledge the contributions of many volunteers to the",
        " * expansion and improvement of this dictionary.",
        " * THIS SOFTWARE IS PROVIDED BY CARNEGIE MELLON UNIVERSITY ``AS IS'' AND ANY EXPRESSED OR IMPLIED WARRANTIES,",
        " * INCLUDING, BUT NOT LIMITED TO, THE IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS FOR A PARTICULAR PURPOSE",
        " * ARE DISCLAIMED. IN NO EVENT SHALL CARNEGIE MELLON UNIVERSITY NOR ITS EMPLOYEES BE LIABLE FOR ANY DIRECT,",
        " * INDIRECT, INCIDENTAL, SPECIAL, EXEMPLARY, OR CONSEQUENTIAL DAMAGES (INCLUDING, BUT NOT LIMITED TO, PROCUREMENT",
        " * OF SUBSTITUTE GOODS OR SERVICES; LOSS OF USE, DATA, OR PROFITS; OR BUSINESS INTERRUPTION) HOWEVER CAUSED AND",
        " * ON ANY THEORY OF LIABILITY, WHETHER IN CONTRACT, STRICT LIABILITY, OR TORT (INCLUDING NEGLIGENCE OR OTHERWISE)",
        " * ARISING IN ANY WAY OUT OF THE USE OF THIS SOFTWARE, EVEN IF ADVISED OF THE POSSIBILITY OF SUCH DAMAGE. */",
        "#ifndef CH_DICT_DATA_H",
        "#define CH_DICT_DATA_H",
        "static const struct { const char *w, *p; } CH_DICT[] = {",
    ]
    for w, p in entries:
        out.append('    {"%s", "%s"},' % (w, p))
    out += ["};", "#endif"]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
