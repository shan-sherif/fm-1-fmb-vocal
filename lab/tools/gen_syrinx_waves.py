# fm-1-chimera-vocal: the syrinx's valve opening over one cycle, for each cell of CHIMERA's (alpha, beta) grid
# (sources/syrinx.rs: the Gardner-Mindlin normal form x' = y, y' = -a - b x - x^3 - x^2 y + x^2 - x y; the opening
# clamp((x - lo) / (hi - lo))^2 with the table's lo and hi), as engine/ch_syrinx_waves.h. CHIMERA's labia run freely
# (the airflow does not drive them), so at its pitch each one plays its limit cycle: the FM-1 plays these cycles by
# phase instead of integrating them (two RK4 runs a sample cost ~30 % of a core). Each cycle starts at its widest
# opening, so neighbouring cells line up when blended. A cell without a limit cycle settles: its opening is constant.
#   gen_syrinx_waves.py ../external/chimera-vocal-synth/crates/chimera/src/sources/syrinxTable.generated.json \
#       > ../engine/ch_syrinx_waves.h
import json
import math
import sys

N = 64                                       # points a cycle


def fill(t):                                  # syrinx.rs build()'s fill, as gen_syrinx_header.py
    al, be, T, lo, hi = t["alphas"], t["betas"], t["T"], t["lo"], t["hi"]

    def at(g, i, j):
        return g[i][j] if i < len(g) and j < len(g[i]) and g[i][j] is not None else None

    for bi in range(len(be)):
        for ai in reversed(range(len(al))):
            v = T[bi][ai]
            if v is None or not math.isfinite(v):
                r = at(T, bi, ai + 1)
                T[bi][ai] = r if r is not None else (at(T, bi + 1, ai) if at(T, bi + 1, ai) is not None else 10.0)
                lo[bi][ai] = at(lo, bi, ai + 1) if at(lo, bi, ai + 1) is not None else -1.0
                hi[bi][ai] = at(hi, bi, ai + 1) if at(hi, bi, ai + 1) is not None else 1.0
    fin = lambda g: [[x if x is not None else 0.0 for x in r] for r in g]
    return al, be, fin(T), fin(lo), fin(hi)


def rhs(x, y, a, b):
    return y, -a - b * x - x * x * x - x * x * y + x * x - x * y


def rk4(x, y, a, b, h):
    k1 = rhs(x, y, a, b)
    k2 = rhs(x + .5 * h * k1[0], y + .5 * h * k1[1], a, b)
    k3 = rhs(x + .5 * h * k2[0], y + .5 * h * k2[1], a, b)
    k4 = rhs(x + h * k3[0], y + h * k3[1], a, b)
    return x + h / 6 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0]), y + h / 6 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1])


def cycle(a, b, T, lo, hi):
    """the opening over one period T (in tau), from its widest point, N points"""
    h = 0.005
    x, y = 0.2, 0.0
    for _ in range(int(60 * T / h)):          # settle onto the limit cycle
        x, y = rk4(x, y, a, b, h)
        if not math.isfinite(x) or abs(x) > 10:
            x, y = 0.2, 0.0
    # one more period, finely: find the widest point (x's maximum), then sample a period from there
    pts = []
    for _ in range(int(2 * T / h) + 2):
        pts.append(x)
        x, y = rk4(x, y, a, b, h)
    per = int(round(T / h))
    i0 = max(range(per), key=lambda i: pts[i])
    out = []
    for k in range(N):
        f = i0 + k * per / N
        i = int(f)
        xx = pts[i] + (pts[i + 1] - pts[i]) * (f - i)
        u = min(1.0, max(0.0, (xx - lo) / max(1e-3, hi - lo)))
        out.append(u * u)
    return out


def main(path):
    al, be, T, lo, hi = fill(json.load(open(path)))
    o = ["/* SPDX-License-Identifier: MIT",
         " * The syrinx's valve opening over one cycle per (alpha, beta) cell of CHIMERA's grid (Jameson Hodge, MIT),",
         " * from its widest point. Generated by lab/tools/gen_syrinx_waves.py: do not edit. */",
         f"#define SYR_WN {N}",
         f"static const float SYR_WAVE[{len(be)}][{len(al)}][SYR_WN] = {{"]
    for bi, b in enumerate(be):
        o.append("  {")
        for ai, a in enumerate(al):
            w = cycle(a, b, T[bi][ai], lo[bi][ai], hi[bi][ai])
            o.append("    {" + ", ".join(f"{v:.5f}f" for v in w) + "},")
        o.append("  },")
        print(f"beta {bi + 1}/{len(be)}", file=sys.stderr)
    o.append("};")
    print("\n".join(o))


if __name__ == "__main__":
    main(sys.argv[1])
