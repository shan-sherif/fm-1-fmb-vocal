# English presets (its Sing mode's default lyric, its demo song "Made of air", Twinkle, its Speak panel's examples),
# with CMUdict's pronunciation of each word the firmware's built-in table lacks, as the Studio sends them
# (app/web/studio.html documentText: not a homograph, not built in).
#
#   gen_words_default.py ../external/chimera-vocal-synth/public/data/cmudict.txt.gz ../engine/ch_dict_data.h > ../app/dsp/words_default.h
import gzip
import re
import sys

# CHIMERA's (MIT, Jameson Hodge): src/ui/singing.ts DEFAULT_LYRICS, crates/chimera/src/phonetics/songs.rs ("Made of
# air", "Twinkle, twinkle"), src/ui/components/SpeakPanel.tsx EXAMPLES. The Studio's PRESETS are the same lines.
PRESETS = [
    "Hello there, I am a voice made of air.",
    "Breathe in, breathe out, I am made of air.",
    "Tongue and lips and throat, singing anywhere.",
    "Twinkle twinkle little star, how I wonder what you are.",
    "Hello. Can you hear me?",
    "She sells sea shells by the sea shore.",
    "Every sound here is air moving through a throat.",
    "The quick brown fox jumps over the lazy dog.",
]
HOMOGRAPHS = {"wind", "read", "live", "lead", "close", "wound"}


def main(dict_gz, dict_h):
    builtin = dict(re.findall(r'\{"([^"]+)", "([^"]+)"\}', open(dict_h, encoding="utf-8").read()))
    cmu = {}
    for line in gzip.open(dict_gz, "rt", encoding="utf-8"):
        w, _, p = line.rstrip("\n").partition("\t")
        if p and w not in cmu:
            cmu[w] = p
    doc = "VOCALWORDS 1\n" + "".join(f"{i + 1} {t}\n" for i, t in enumerate(PRESETS))
    send = {}
    for t in PRESETS:
        for tok in re.findall(r"[A-Za-z'][A-Za-z'\-]*", t):
            for part in [p for p in tok.split("-") if p]:
                c = part.lower().strip("'")
                if c in HOMOGRAPHS or c in builtin or c not in cmu:
                    continue
                send[c] = cmu[c]
    doc += "".join(f"@{w} {p}\n" for w, p in send.items())
    body = "".join('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"\n' for line in doc.splitlines())
    print(f"""/* SPDX-License-Identifier: MIT AND BSD-2-Clause
 * Copyright (c) 2026 Jameson Hodge (CHIMERA, https://github.com/jamesondh/chimera-vocal-synth): the preset lines
 * Generated by lab/tools/gen_words_default.py: do not edit. The word slots before the Studio sends any:
 * CHIMERA's English presets (MIT, Jameson Hodge), {len(send)} pronunciations from CMUdict ({len(doc)} bytes).
 * CMUdict: Copyright (C) 1993-2015 Carnegie Mellon University. All rights reserved. BSD-style licence: see
 * engine/ch_dict_data.h for its notice. */
#ifndef WORDS_DEFAULT_H
#define WORDS_DEFAULT_H
static const char WORDS_DEFAULT[] =
{body.rstrip()};
#endif""")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
