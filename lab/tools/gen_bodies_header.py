import json
import math
import struct
import sys
from pathlib import Path

ART_MAGIC = 4.0e9 + 1730.0
NAMES = ("MALE", "FEMALE", "CHILD")
F0 = (112.0, 205.0, 250.0)          # the speaking pitch, as the lab renders CHIMERA (lab/src/main.rs speaking())
# CHIMERA's calibrated vowels: each body's F1 and F2 against the male's (the vowel pad's ranges scale by them)
VOWELS = Path(__file__).resolve().parents[2] / "external" / "chimera-vocal-synth" / "crates" / "chimera" / "src" / \
    "phonetics" / "vowelTargets.generated.json"


def pad_scale(cal, body):
    """the geometric mean of body / male for F1 and F2 over the vowels both have"""
    m, b = cal["male"], cal[body]
    r = [[], []]
    for ipa, v in m.items():
        if ipa in b and v["formants"][0] > 0 and b[ipa]["formants"][0] > 0:
            for i in (0, 1):
                r[i].append(math.log(b[ipa]["formants"][i] / v["formants"][i]))
    return [math.exp(sum(x) / len(x)) for x in r]


def head(path):
    b = open(path, "rb").read()
    v = struct.unpack("<%dd" % (len(b) // 8), b)
    assert v[0] == ART_MAGIC and v[1] == 1.0, "not a version 1 articulation file"
    return v[2:2 + 36]


def main(paths):
    hs = [head(p) for p in paths]
    cal = json.load(open(VOWELS))
    pads = [pad_scale(cal, b) for b in ("male", "female", "child")]
    f = lambda x: repr(float(x)) + "f"
    common = hs[0]
    for h in hs[1:]:                 # what is the same for every body goes in once
        for i in (0, 5, 6, 7, 9) + tuple(range(19, 36)):
            assert h[i] == common[i], "the bodies differ at %d" % i
    out = []
    w = out.append
    w("/* SPDX-License-Identifier: MIT")
    w(" * Copyright (c) 2026 Jameson Hodge (CHIMERA, https://github.com/jamesondh/chimera-vocal-synth)")
    w(" * GENERATED by lab/tools/gen_bodies_header.py from `lab record` articulation files: do not edit.")
    w(" * CHIMERA's three bodies (HumanBody: adult male, adult female, child) as the anatomy and the waveguide take them:")
    w(" * the dimensions, the airway network's indices (a shorter trachea for a smaller body), the speaking pitch, the")
    w(" * vowels' formants against the male's. */")
    w("#ifndef VOICE_BODIES_H\n#define VOICE_BODIES_H\n#include \"ch_tract.h\"\n")
    w("#define NBODIES 3")
    w("typedef struct {")
    w("    const char *name;")
    w("    float scale, pharynx, tongue_radius, lip_width, f0;")
    w("    float pad_f1, pad_f2;            /* its vowels' F1 and F2 against the male's (CHIMERA's calibration) */")
    w("    uint8_t tr_n, ph_first, ph_branch, or_first, or_branch, glottis_port, velum_port;")
    w("} ch_body_t;")
    w("static const ch_body_t CH_BODIES[NBODIES] = {")
    for name, h, f0, pad in zip(NAMES, hs, F0, pads):
        w("    {\"%s\", %s, %s, %s, %s, %s, %s, %s, %d, %d, %d, %d, %d, %d, %d}," % (
            name, f(h[1]), f(h[2]), f(h[3]), f(h[4]), f(f0), f(round(pad[0], 4)), f(round(pad[1], 4)),
            int(h[10]), int(h[11]), int(h[12]), int(h[14]), int(h[15]), int(h[17]), int(h[18])))
    w("};\n")
    c = common
    w("""/* the anatomy's settings for body d (ch_tract_init): all the waveguide (ch_wave.c) needs. d: one of CH_BODIES, or a
 * blend of them (the app's: CHIMERA's BodyMix, the airway's indices the nearest body's) */
static void body_tract_setup(ch_tract_t *t, const ch_body_t *d)
{
    t->fs = %s; t->n_ph = %d; t->n_or = %d; t->dx_stable = %s;
    t->tr_branch = %d; t->tr_n = d->tr_n; t->ph_first = d->ph_first; t->ph_branch = d->ph_branch;
    t->or_first = d->or_first; t->or_branch = d->or_branch; t->glottis_port = d->glottis_port; t->velum_port = d->velum_port;
    t->gain_glottis = %s; t->gain_constriction = %s; t->gain_teeth = %s;
    t->max_area_rate = %s; t->area_rate_gain = %s; t->seal_rate = %s; t->seal_lo = %s; t->seal_hi = %s; t->seal_ease = %s;
    t->law[0] = %s; t->law[1] = %s; t->law[2] = %s; t->law[3] = %s; t->law[4] = %s; t->law[5] = %s; t->law[6] = %s; t->law[7] = %s;
    ch_tract_init(t, d->scale, d->pharynx, d->tongue_radius, d->lip_width);
}
#endif""" % (f(c[0]), int(c[5]), int(c[6]), f(c[7]), int(c[9]), *map(f, c[19:22]), *map(f, c[22:28]), *map(f, c[28:36])))
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1:4])
