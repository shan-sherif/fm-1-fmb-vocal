# LICENSES/SCOWL.txt), kept where CMUdict has a pronunciation, plain lower-case words of 3 to 9 letters (no names, no
# abbreviations), one a line, as app/web/random_words.txt (the site serves it beside the Studio).
#
#   curl -L -o scowl.tar.gz https://downloads.sourceforge.net/project/wordlist/SCOWL/2020.12.07/scowl-2020.12.07.tar.gz
#   tar -xzf scowl.tar.gz
#   gen_random_words.py scowl-2020.12.07/final ../external/chimera-vocal-synth/public/data/cmudict.txt.gz \
#       > ../app/web/random_words.txt
import gzip
import re
import sys
from pathlib import Path


def main(final_dir, cmudict_gz):
    words = set()
    for level in ("10", "20"):
        for w in (Path(final_dir) / f"english-words.{level}").read_text(encoding="latin-1").split():
            if re.fullmatch(r"[a-z]{3,9}", w):
                words.add(w)
    known = set()
    for line in gzip.open(cmudict_gz, "rt", encoding="utf-8"):
        w = line.split("\t", 1)[0]
        if w in words:
            known.add(w)
    print("# The Studio's random words: SCOWL's levels 10 and 20 (Copyright 2000-2018 Kevin Atkinson; LICENSES/SCOWL.txt),")
    print("# kept where CMUdict has a pronunciation. Generated by lab/tools/gen_random_words.py: do not edit.")
    print("\n".join(sorted(known)))
    print(f"{len(known)} of {len(words)} words", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
